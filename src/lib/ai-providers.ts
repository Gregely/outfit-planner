export function providerKindOf(id: string): ProviderKind {
  if (id === "anthropic" || id === "openai" || id === "gemini") return id;
  return "openai-compatible";
}

/** "Claude · claude-opus-5-5" style label for attribution. */
export function generatedByLabel(g: { providerLabel?: string | null; model?: string | null } | null | undefined) {
  if (!g) return null;
  return [g.providerLabel, g.model].filter(Boolean).join(" · ") || null;
}

